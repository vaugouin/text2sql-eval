SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

-- 1. 2830 and 2832 EN carry a JSON_RESULT but no score and no timings: was phase 20 never run on
--    these rows, or are they duplicated / deleted?
SELECT ID_ROW, ID_T2S_EVALUATION, LANG, DELETED, CACHE_PASS, RESULT_ENTITY_MODEL, ANSWER_SINGLE_VALUE_MODEL,
       TIM_EXECUTION, TIM_UPDATED, ASSERTIONS_TOTAL_SCORE, TOTAL_PROCESSING_TIME,
       LENGTH(JSON_RESULT) AS JSON_LEN, JSON_VALID(JSON_RESULT) AS JSON_OK
FROM T_WC_T2S_EVALUATION_EXECUTION
WHERE ID_T2S_EVALUATION IN (2829, 2830, 2831, 2832, 2833) AND API_VERSION = '001.001.020'
ORDER BY ID_T2S_EVALUATION, LANG, ID_ROW;

-- 2. 2864: "Osgar" against the Oscars. Which award rows the resolution could have picked, and
--    how many Academy Award wins Meryl Streep (5064) has, by award and by parent award.
SELECT ID_AWARD, ID_WIKIDATA, AWARD_NAME, AWARD_NAME_FR, AWARD_TYPE, ID_AWARD_PARENT, PERSON_COUNT, MOVIE_COUNT, DELETED
FROM T_WC_T2S_AWARD
WHERE AWARD_NAME IN ('Osgar', 'Oscar', 'Oscars', 'Academy Awards', 'Academy Award')
   OR AWARD_NAME LIKE 'Osgar%' OR ID_AWARD = 30680
ORDER BY ID_AWARD;

SELECT a.ID_AWARD, a.AWARD_NAME, a.ID_AWARD_PARENT, p.AWARD_NAME AS PARENT_NAME, pa.AWARD_YEAR
FROM T_WC_T2S_PERSON_AWARD pa
JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = pa.ID_AWARD
LEFT JOIN T_WC_T2S_AWARD p ON p.ID_AWARD = a.ID_AWARD_PARENT
WHERE pa.ID_PERSON = 5064 AND pa.DELETED = 0
  AND (a.AWARD_NAME LIKE 'Academy Award%' OR p.AWARD_NAME LIKE 'Academy Award%')
ORDER BY pa.AWARD_YEAR;

-- 3. 2898 / 2919: birth countries of the Palme d'Or directors. Format of COUNTRY_OF_BIRTH and
--    the expected top three (the assertion wants US, IT, FR).
SELECT ID_AWARD, AWARD_NAME, AWARD_NAME_FR, MOVIE_COUNT, PERSON_COUNT
FROM T_WC_T2S_AWARD WHERE AWARD_NAME LIKE 'Palme d%Or%' ORDER BY ID_AWARD;

SELECT dir.COUNTRY_OF_BIRTH, COUNT(DISTINCT dir.ID_PERSON) AS DIRECTORS
FROM T_WC_T2S_MOVIE_AWARD ma
JOIN T_WC_T2S_AWARD a ON a.ID_AWARD = ma.ID_AWARD AND a.AWARD_NAME = 'Palme d''Or'
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = ma.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON dir ON dir.ID_PERSON = pm.ID_PERSON
WHERE ma.DELETED = 0
GROUP BY dir.COUNTRY_OF_BIRTH
ORDER BY DIRECTORS DESC
LIMIT 10;

-- 4. 2899: production countries of The Fellowship of the Ring (120) are in
--    T_WC_T2S_MOVIE_PRODUCTION_COUNTRY; the API read the filming locations.
SELECT ID_MOVIE, COUNTRY_CODE, DELETED FROM T_WC_T2S_MOVIE_PRODUCTION_COUNTRY WHERE ID_MOVIE = 120;
SELECT l.LOCATION_NAME, l.LOCATION_TYPE FROM T_WC_T2S_MOVIE_LOCATION ml
JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = ml.ID_LOCATION WHERE ml.ID_MOVIE = 120 AND l.LOCATION_TYPE = 'country';

-- 5. 2925: the companies named Time Warner, and how many children each has.
SELECT c.ID_COMPANY, c.COMPANY_NAME, c.ID_PARENT, c.MOVIE_COUNT, c.SERIE_COUNT,
       (SELECT COUNT(*) FROM T_WC_T2S_COMPANY k WHERE k.ID_PARENT = c.ID_COMPANY AND k.DELETED = 0) AS CHILDREN
FROM T_WC_T2S_COMPANY c
WHERE c.COMPANY_NAME LIKE '%Time Warner%' OR c.COMPANY_NAME = 'WarnerMedia' OR c.COMPANY_NAME LIKE 'Warner Bros. Discovery%'
ORDER BY CHILDREN DESC, c.ID_COMPANY;

-- 6. 2921 / 2927: the collections that hold the Star Wars and Middle-earth films (is there a
--    trilogy level under a saga collection at all?).
SELECT co.ID_T2S_COLLECTION, co.COLLECTION_NAME, COUNT(mc.ID_MOVIE) AS MOVIES
FROM T_WC_T2S_COLLECTION co
JOIN T_WC_T2S_MOVIE_COLLECTION mc ON mc.ID_T2S_COLLECTION = co.ID_T2S_COLLECTION AND mc.DELETED = 0
WHERE mc.ID_MOVIE IN (11, 1891, 1892, 1893, 1894, 1895, 140607, 181808, 181812,
                      120, 121, 122, 49051, 57158, 122917)
GROUP BY co.ID_T2S_COLLECTION, co.COLLECTION_NAME
ORDER BY co.COLLECTION_NAME;

-- 7. 2840 FR: French titles of The Godfather films.
SELECT ID_MOVIE, MOVIE_TITLE, MOVIE_TITLE_FR, ORIGINAL_TITLE, RUNTIME FROM T_WC_T2S_MOVIE WHERE ID_MOVIE IN (238, 240);

-- 8. 2817 FR: how Chaplin's (13848) tramp is credited.
SELECT pm.CAST_CHARACTER, COUNT(*) AS FILMS
FROM T_WC_T2S_PERSON_MOVIE pm
WHERE pm.ID_PERSON = 13848 AND pm.CREDIT_TYPE = 'cast' AND pm.DELETED = 0
GROUP BY pm.CAST_CHARACTER ORDER BY FILMS DESC LIMIT 15;

SELECT ID_CHARACTER, CAST_CHARACTER, WIKIDATA_NAME, MOVIE_COUNT FROM T_WC_T2S_CHARACTER
WHERE CAST_CHARACTER IN ('The Tramp', 'Little Tramp', 'A Tramp', 'Tramp', 'Charlot') OR WIKIDATA_NAME IN ('The Tramp', 'Tramp') LIMIT 20;

-- 9. 2852 EN: the films titled Vertigo, with their votes (Hitchcock's is 426).
SELECT ID_MOVIE, MOVIE_TITLE, ORIGINAL_TITLE, DAT_RELEASE, IMDB_VOTES, POPULARITY
FROM T_WC_T2S_MOVIE WHERE MOVIE_TITLE = 'Vertigo' OR ORIGINAL_TITLE = 'Vertigo'
ORDER BY IMDB_VOTES DESC LIMIT 15;

-- 10. 2909 FR: The Sopranos (1398) and The Wire (1438), and the size of the HBO set.
SELECT ID_SERIE, SERIE_TITLE, IMDB_RATING, NUMBER_OF_SEASONS FROM T_WC_T2S_SERIE WHERE ID_SERIE IN (1398, 1438);

-- 11. Chains 2932, 2933, 2935, 2936, 2939: the source links of the films the assertions expect.
SELECT msw.ID_MOVIE, m.MOVIE_TITLE, sw.ID_SOURCE_WORK, sw.SOURCE_WORK_NAME, sw.SOURCE_WORK_TYPE,
       sw.SOURCE_WORK_YEAR, sw.ID_MOVIE AS SW_ID_MOVIE, sw.ID_SERIE AS SW_ID_SERIE
FROM T_WC_T2S_MOVIE_SOURCE_WORK msw
JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = msw.ID_MOVIE
JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = msw.ID_SOURCE_WORK
WHERE msw.DELETED = 0
  AND (msw.ID_MOVIE IN (111, 877, 1422, 10775, 426063, 653, 6404, 9691, 11878, 391, 966, 346)
       OR sw.ID_SOURCE_WORK IN (7931, 5212, 11237, 7219, 6848))
ORDER BY msw.ID_MOVIE, sw.ID_SOURCE_WORK;

SELECT ID_SOURCE_WORK, SOURCE_WORK_NAME, SOURCE_WORK_TYPE, SOURCE_WORK_FORM, SOURCE_WORK_YEAR, ID_MOVIE, ID_SERIE
FROM T_WC_T2S_SOURCE_WORK WHERE ID_SOURCE_WORK IN (7931, 5212, 11237, 7219, 6848);
