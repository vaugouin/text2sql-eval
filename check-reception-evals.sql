-- check-reception-evals.sql
-- Read-only checks before writing the critical reception evaluations (TEXT2SQL-EVAL-015).
--   1. the label ids, so the sql_query assertions name the right ID_RECEPTION_LABEL;
--   2. how many of the films read by the reception labelling have Rotten Tomatoes and
--      Metacritic scores in OMDb (T_WC_OMDB_TITLE, the chosen source for those two scores),
--      against what the Wikipedia pages quoted (T_WC_T2S_MOVIE_RECEPTION);
--   3. the number of rows each proposed question should return, so no evaluation asks for
--      data the base lacks.
-- T_WC_T2S_MOVIE.ID_IMDB is utf8mb4_general_ci and T_WC_OMDB_TITLE.ID_IMDB utf8mb4_unicode_ci:
-- the join names OMDb's collation so that its primary key stays usable.
-- ROTTEN_TOMATOES_PCT is TINYINT UNSIGNED: the gap is computed after a CAST to SIGNED, otherwise
-- a lower Wikipedia figure makes the subtraction overflow (error 1690 on the first run).

SELECT ID_RECEPTION_LABEL, LABEL_CODE, LABEL_GROUP, MOVIE_COUNT
FROM T_WC_T2S_RECEPTION_LABEL ORDER BY DISPLAY_ORDER;

SELECT COUNT(*) AS OMDB_ROWS, SUM(RESPONSE_OK = 1) AS OMDB_OK, SUM(OMDB_TYPE = 'movie') AS OMDB_MOVIES,
       SUM(RT_SCORE IS NOT NULL) AS WITH_RT, SUM(METACRITIC_SCORE IS NOT NULL) AS WITH_METACRITIC,
       SUM(METASCORE IS NOT NULL) AS WITH_METASCORE, MIN(TIM_OMDB_FETCHED) AS FIRST_FETCH, MAX(TIM_OMDB_FETCHED) AS LAST_FETCH
FROM T_WC_OMDB_TITLE;

SELECT COUNT(*) AS FILMS_READ,
       SUM(m.ID_MOVIE IS NOT NULL) AS WITH_T2S_MOVIE,
       SUM(m.ID_IMDB LIKE 'tt%') AS WITH_IMDB_ID,
       SUM(o.ID_IMDB IS NOT NULL) AS IN_OMDB,
       SUM(o.RESPONSE_OK = 1) AS OMDB_OK,
       SUM(o.RT_SCORE IS NOT NULL) AS OMDB_RT,
       SUM(o.METACRITIC_SCORE IS NOT NULL OR o.METASCORE IS NOT NULL) AS OMDB_METACRITIC,
       SUM(r.ROTTEN_TOMATOES_PCT IS NOT NULL) AS WIKI_RT,
       SUM(r.METACRITIC_SCORE IS NOT NULL) AS WIKI_METACRITIC,
       SUM(r.ROTTEN_TOMATOES_PCT IS NOT NULL AND o.RT_SCORE IS NULL) AS WIKI_RT_ONLY,
       SUM(r.METACRITIC_SCORE IS NOT NULL AND o.METACRITIC_SCORE IS NULL AND o.METASCORE IS NULL) AS WIKI_METACRITIC_ONLY,
       ROUND(AVG(CASE WHEN r.ROTTEN_TOMATOES_PCT IS NOT NULL AND o.RT_SCORE IS NOT NULL
                      THEN ABS(CAST(r.ROTTEN_TOMATOES_PCT AS SIGNED) - o.RT_SCORE) END), 1) AS RT_MEAN_GAP_POINTS,
       SUM(r.CINEMASCORE IS NOT NULL) AS WITH_CINEMASCORE
FROM T_WC_T2S_MOVIE_RECEPTION r
LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = r.ID_MOVIE
LEFT JOIN T_WC_OMDB_TITLE o ON o.ID_IMDB = m.ID_IMDB COLLATE utf8mb4_unicode_ci
WHERE COALESCE(r.DELETED, 0) = 0;

-- Rows per proposed question (EN wording; the French twins ask the same thing).
SELECT 'Q01 cult films of the 1980s' AS QUESTION, COUNT(DISTINCT m.ID_MOVIE) AS ANSWER_ROWS
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'cult' AND m.RELEASE_YEAR BETWEEN 1980 AND 1989
UNION ALL
SELECT 'Q02 Ridley Scott box office bombs', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = m.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pm.ID_PERSON
WHERE l.LABEL_CODE = 'box_office_bomb' AND p.PERSON_NAME = 'Ridley Scott'
UNION ALL
SELECT 'Q03 banned, DETAIL like United Kingdom', COUNT(DISTINCT ml.ID_MOVIE)
FROM T_WC_T2S_MOVIE_RECEPTION_LABEL ml JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'banned' AND ml.ID_MOVIE IS NOT NULL AND ml.DETAIL LIKE '%United Kingdom%'
UNION ALL
SELECT 'Q03b banned, DETAIL like UK or Britain but not United Kingdom', COUNT(DISTINCT ml.ID_MOVIE)
FROM T_WC_T2S_MOVIE_RECEPTION_LABEL ml JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'banned' AND ml.ID_MOVIE IS NOT NULL AND ml.DETAIL NOT LIKE '%United Kingdom%'
  AND (ml.DETAIL LIKE '%Britain%' OR ml.DETAIL LIKE '% UK%' OR ml.DETAIL LIKE 'UK%' OR ml.DETAIL LIKE '%England%')
UNION ALL
SELECT 'Q04 critically acclaimed science fiction', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
JOIN T_WC_T2S_MOVIE_GENRE mg ON mg.ID_MOVIE = m.ID_MOVIE JOIN T_WC_T2S_GENRE g ON g.ID_GENRE = mg.ID_GENRE
WHERE l.LABEL_CODE = 'critics_acclaimed' AND g.GENRE_NAME = 'Science Fiction'
UNION ALL
SELECT 'Q05 notoriously bad horror films', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
JOIN T_WC_T2S_MOVIE_GENRE mg ON mg.ID_MOVIE = m.ID_MOVIE JOIN T_WC_T2S_GENRE g ON g.ID_GENRE = mg.ID_GENRE
WHERE l.LABEL_CODE = 'notoriously_bad' AND g.GENRE_NAME = 'Horror'
UNION ALL
SELECT 'Q06 Stanley Kubrick controversial', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = m.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pm.ID_PERSON
WHERE l.LABEL_CODE = 'controversial' AND p.PERSON_NAME = 'Stanley Kubrick'
UNION ALL
SELECT 'Q07 number of cult films', COUNT(DISTINCT ml.ID_MOVIE)
FROM T_WC_T2S_MOVIE_RECEPTION_LABEL ml JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'cult' AND ml.ID_MOVIE IS NOT NULL
UNION ALL
SELECT 'Q08 Alfred Hitchcock censored', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = m.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pm.ID_PERSON
WHERE l.LABEL_CODE = 'censored' AND p.PERSON_NAME = 'Alfred Hitchcock'
UNION ALL
SELECT 'Q09 box office records in the 1990s', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'box_office_record' AND m.RELEASE_YEAR BETWEEN 1990 AND 1999
UNION ALL
SELECT 'Q10 divided the critics, 2010s', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'critics_polarized' AND m.RELEASE_YEAR BETWEEN 2010 AND 2019
UNION ALL
SELECT 'Q11 reappraised over time', COUNT(DISTINCT ml.ID_MOVIE)
FROM T_WC_T2S_MOVIE_RECEPTION_LABEL ml JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'reappraised' AND ml.ID_MOVIE IS NOT NULL
UNION ALL
SELECT CONCAT('Q12 Oppenheimer (2023) labels: ', COALESCE(GROUP_CONCAT(l.LABEL_CODE ORDER BY l.DISPLAY_ORDER), 'none')), COUNT(*)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE m.MOVIE_TITLE = 'Oppenheimer' AND m.RELEASE_YEAR = 2023
UNION ALL
SELECT 'Q13 Christopher Nolan hits with positive or acclaimed reviews', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = m.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pm.ID_PERSON
WHERE p.PERSON_NAME = 'Christopher Nolan'
  AND EXISTS (SELECT 1 FROM T_WC_T2S_MOVIE_RECEPTION_LABEL a JOIN T_WC_T2S_RECEPTION_LABEL la ON la.ID_RECEPTION_LABEL = a.ID_RECEPTION_LABEL
              WHERE a.ID_MOVIE = m.ID_MOVIE AND la.LABEL_CODE = 'box_office_hit')
  AND EXISTS (SELECT 1 FROM T_WC_T2S_MOVIE_RECEPTION_LABEL b JOIN T_WC_T2S_RECEPTION_LABEL lb ON lb.ID_RECEPTION_LABEL = b.ID_RECEPTION_LABEL
              WHERE b.ID_MOVIE = m.ID_MOVIE AND lb.LABEL_CODE IN ('critics_positive', 'critics_acclaimed'))
UNION ALL
SELECT 'Q14 Martin Scorsese films, OMDb Rotten Tomatoes >= 90', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m
JOIN T_WC_T2S_PERSON_MOVIE pm ON pm.ID_MOVIE = m.ID_MOVIE AND pm.CREDIT_TYPE = 'crew' AND pm.CREW_JOB = 'Director'
JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = pm.ID_PERSON
JOIN T_WC_OMDB_TITLE o ON o.ID_IMDB = m.ID_IMDB COLLATE utf8mb4_unicode_ci
WHERE p.PERSON_NAME = 'Martin Scorsese' AND o.RT_SCORE >= 90
UNION ALL
SELECT CONCAT('Q15 The Godfather (1972), OMDb Metacritic: ', COALESCE(MAX(o.METACRITIC_SCORE), MAX(o.METASCORE), 'none'),
              ', Rotten Tomatoes: ', COALESCE(MAX(o.RT_SCORE), 'none')), COUNT(*)
FROM T_WC_T2S_MOVIE m JOIN T_WC_OMDB_TITLE o ON o.ID_IMDB = m.ID_IMDB COLLATE utf8mb4_unicode_ci
WHERE m.MOVIE_TITLE = 'The Godfather' AND m.RELEASE_YEAR = 1972
UNION ALL
SELECT 'Q16 films of 2023 with an OMDb Metacritic score', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_OMDB_TITLE o ON o.ID_IMDB = m.ID_IMDB COLLATE utf8mb4_unicode_ci
WHERE m.RELEASE_YEAR = 2023 AND COALESCE(o.METACRITIC_SCORE, o.METASCORE) IS NOT NULL
UNION ALL
SELECT 'Q17 critically acclaimed films with an IMDb rating below 6', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_T2S_MOVIE_RECEPTION_LABEL ml ON ml.ID_MOVIE = m.ID_MOVIE
JOIN T_WC_T2S_RECEPTION_LABEL l ON l.ID_RECEPTION_LABEL = ml.ID_RECEPTION_LABEL
WHERE l.LABEL_CODE = 'critics_acclaimed' AND m.IMDB_RATING < 6
UNION ALL
SELECT 'Q18 OMDb Rotten Tomatoes >= 90 and IMDb rating below 6 (critics loved, audience did not)', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m JOIN T_WC_OMDB_TITLE o ON o.ID_IMDB = m.ID_IMDB COLLATE utf8mb4_unicode_ci
WHERE o.RT_SCORE >= 90 AND m.IMDB_RATING < 6 AND m.IMDB_VOTES >= 1000
UNION ALL
SELECT 'Q19 films with an A+ CinemaScore', COUNT(DISTINCT r.ID_MOVIE)
FROM T_WC_T2S_MOVIE_RECEPTION r
WHERE r.CINEMASCORE = 'A+' AND r.ID_MOVIE IS NOT NULL
UNION ALL
SELECT 'Q20 box office bombs that became cult films', COUNT(DISTINCT m.ID_MOVIE)
FROM T_WC_T2S_MOVIE m
WHERE EXISTS (SELECT 1 FROM T_WC_T2S_MOVIE_RECEPTION_LABEL a JOIN T_WC_T2S_RECEPTION_LABEL la ON la.ID_RECEPTION_LABEL = a.ID_RECEPTION_LABEL
              WHERE a.ID_MOVIE = m.ID_MOVIE AND la.LABEL_CODE = 'box_office_bomb')
  AND EXISTS (SELECT 1 FROM T_WC_T2S_MOVIE_RECEPTION_LABEL b JOIN T_WC_T2S_RECEPTION_LABEL lb ON lb.ID_RECEPTION_LABEL = b.ID_RECEPTION_LABEL
              WHERE b.ID_MOVIE = m.ID_MOVIE AND lb.LABEL_CODE = 'cult');
