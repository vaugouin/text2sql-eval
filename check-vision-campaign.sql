SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Score per vision model and language (live rows)' AS SECTION;
SELECT VISION_MODEL, LANG, API_VERSION,
       COUNT(*) AS EXECUTIONS,
       COUNT(DISTINCT ID_T2S_EVALUATION) AS EVALUATIONS,
       SUM(ASSERTIONS_VISION_IDENTIFICATION_SCORE = 1) AS IDENTIFIED,
       SUM(ASSERTIONS_VISION_IDENTIFICATION_SCORE = 0) AS MISSED,
       SUM(ASSERTIONS_VISION_IDENTIFICATION_SCORE IS NULL) AS NOT_SCORED,
       ROUND(AVG(VISION_IDENTIFICATION_PROCESSING_TIME), 1) AS AVG_VISION_SECONDS,
       MIN(DAT_CREAT) AS FIRST_ROW, MAX(DAT_CREAT) AS LAST_ROW
FROM T_WC_T2S_EVALUATION_EXECUTION
WHERE VISION_MODEL IS NOT NULL AND DELETED = 0
GROUP BY VISION_MODEL, LANG, API_VERSION
ORDER BY LANG, VISION_MODEL;

SELECT '2. Per image, both models side by side (latest live row per model and language)' AS SECTION;
WITH LATEST AS (
  SELECT X.*, ROW_NUMBER() OVER (PARTITION BY X.ID_T2S_EVALUATION, X.VISION_MODEL, X.LANG
                                 ORDER BY X.ID_ROW DESC) AS RN
  FROM T_WC_T2S_EVALUATION_EXECUTION X
  WHERE X.VISION_MODEL IS NOT NULL AND X.DELETED = 0
)
SELECT E.ID_T2S_EVALUATION, L.LANG, E.ID_T2S_EVALUATION_CATEGORY AS CAT,
       JSON_VALUE(E.ASSERTIONS_VISION_IDENTIFICATION, '$.type') AS EXPECTED_TYPE,
       JSON_VALUE(E.ASSERTIONS_VISION_IDENTIFICATION, '$.title') AS EXPECTED_TITLE,
       MAX(CASE WHEN L.VISION_MODEL = 'gpt-6-astra' THEN L.ASSERTIONS_VISION_IDENTIFICATION_SCORE END) AS ASTRA,
       MAX(CASE WHEN L.VISION_MODEL = 'claude-fable-5-2' THEN L.ASSERTIONS_VISION_IDENTIFICATION_SCORE END) AS FABLE,
       MAX(CASE WHEN L.VISION_MODEL = 'gpt-6-astra' THEN L.VISION_IDENTIFICATION_PROCESSING_TIME END) AS ASTRA_S,
       MAX(CASE WHEN L.VISION_MODEL = 'claude-fable-5-2' THEN L.VISION_IDENTIFICATION_PROCESSING_TIME END) AS FABLE_S
FROM LATEST L
JOIN T_WC_T2S_EVALUATION E ON E.ID_T2S_EVALUATION = L.ID_T2S_EVALUATION
WHERE L.RN = 1
GROUP BY E.ID_T2S_EVALUATION, L.LANG, E.ID_T2S_EVALUATION_CATEGORY, E.ASSERTIONS_VISION_IDENTIFICATION
ORDER BY L.LANG, E.ID_T2S_EVALUATION;
