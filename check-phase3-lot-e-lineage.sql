-- Phase 3 lot E (chain of adaptations and remakes): the source-work graph around the anchors of
-- evaluations 2930 to 2939 and four probe anchors, 2026-11-12. Read-only (SELECT and WITH
-- RECURSIVE), voie 1:
--   ssh vps-agent pull text2sql-eval
--   ssh vps-agent run text2sql-eval/check-phase3-lot-e-lineage.sql
--
-- Purpose: the API's lineage walk (fastapi-text2sql result_chain.py) cannot run offline. This file
-- dumps, for every anchor, the closure of the graph five generations up and five down (one more
-- than the walk's bound of four, so its depth probe is covered), then every link that touches a
-- node of the closure, in the column layout the walk's own statements return (CHILD_TYPE, CHILD_ID,
-- DISPLAY_ORDER, the source-work columns), and the facts of every node met. From that the session
-- builds an in-memory graph, runs the walk on it, and writes the p3e-* fixtures of both fronts.
--
-- Node keys: m<ID_MOVIE>, s<ID_SERIE>, w<ID_SOURCE_WORK>; a source work whose ID_MOVIE or ID_SERIE
-- is set is that movie or series (a remake), as in the walk.
-- Anchors: Yojimbo m11878, A Star Is Born 1937 m22692, Scarface 1932 m877, Nosferatu 1922 m653
-- (the four probes), and A Star Is Born 2018 m332562, A Fistful of Dollars m391, Scarface 1983
-- m111, The Departed m1422, The Magnificent Seven 2016 m333484 and 1960 m966, Nosferatu 2024
-- m426063, Last Man Standing m9333, Red Harvest w6848, Seven Samurai m346 (2930 to 2939).

SELECT 'E1 closure size per anchor' AS block, NOW(6) AS t;
WITH RECURSIVE e AS (
  SELECT CONCAT('m', j.ID_MOVIE) AS CHILD_KEY,
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END AS PARENT_KEY
  FROM T_WC_T2S_MOVIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
  UNION ALL
  SELECT CONCAT('s', j.ID_SERIE),
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END
  FROM T_WC_T2S_SERIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
),
a AS (
  SELECT 'm11878' AS K UNION ALL SELECT 'm22692' UNION ALL SELECT 'm877' UNION ALL SELECT 'm653'
  UNION ALL SELECT 'm332562' UNION ALL SELECT 'm391' UNION ALL SELECT 'm111' UNION ALL SELECT 'm1422'
  UNION ALL SELECT 'm333484' UNION ALL SELECT 'm966' UNION ALL SELECT 'm426063' UNION ALL SELECT 'm9333'
  UNION ALL SELECT 'w6848' UNION ALL SELECT 'm346'
),
up AS (
  SELECT K AS ANCHOR, K AS NODE, 0 AS D FROM a
  UNION
  SELECT up.ANCHOR, e.PARENT_KEY, up.D + 1 FROM up JOIN e ON e.CHILD_KEY = up.NODE WHERE up.D < 5
),
down AS (
  SELECT K AS ANCHOR, K AS NODE, 0 AS D FROM a
  UNION
  SELECT down.ANCHOR, e.CHILD_KEY, down.D + 1 FROM down JOIN e ON e.PARENT_KEY = down.NODE WHERE down.D < 5
)
SELECT x.ANCHOR, x.WAY, COUNT(DISTINCT x.NODE) AS nodes, MAX(x.D) AS deepest
FROM (SELECT ANCHOR, 'up' AS WAY, NODE, D FROM up UNION ALL SELECT ANCHOR, 'down', NODE, D FROM down) x
GROUP BY x.ANCHOR, x.WAY ORDER BY x.ANCHOR, x.WAY;

SELECT 'E2 links touching the closure (walk layout)' AS block, NOW(6) AS t;
WITH RECURSIVE e AS (
  SELECT CONCAT('m', j.ID_MOVIE) AS CHILD_KEY,
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END AS PARENT_KEY
  FROM T_WC_T2S_MOVIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
  UNION ALL
  SELECT CONCAT('s', j.ID_SERIE),
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END
  FROM T_WC_T2S_SERIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
),
a AS (
  SELECT 'm11878' AS K UNION ALL SELECT 'm22692' UNION ALL SELECT 'm877' UNION ALL SELECT 'm653'
  UNION ALL SELECT 'm332562' UNION ALL SELECT 'm391' UNION ALL SELECT 'm111' UNION ALL SELECT 'm1422'
  UNION ALL SELECT 'm333484' UNION ALL SELECT 'm966' UNION ALL SELECT 'm426063' UNION ALL SELECT 'm9333'
  UNION ALL SELECT 'w6848' UNION ALL SELECT 'm346'
),
up AS (
  SELECT K AS ANCHOR, K AS NODE, 0 AS D FROM a
  UNION
  SELECT up.ANCHOR, e.PARENT_KEY, up.D + 1 FROM up JOIN e ON e.CHILD_KEY = up.NODE WHERE up.D < 5
),
down AS (
  SELECT K AS ANCHOR, K AS NODE, 0 AS D FROM a
  UNION
  SELECT down.ANCHOR, e.CHILD_KEY, down.D + 1 FROM down JOIN e ON e.PARENT_KEY = down.NODE WHERE down.D < 5
),
nodes AS (SELECT NODE FROM up UNION SELECT NODE FROM down),
links AS (
  SELECT 'movie' AS CHILD_TYPE, j.ID_MOVIE AS CHILD_ID, j.DISPLAY_ORDER, sw.ID_SOURCE_WORK, sw.SOURCE_WORK_TYPE,
         sw.SOURCE_WORK_FORM, sw.ID_MOVIE, sw.ID_SERIE, sw.SOURCE_WORK_NAME, sw.SOURCE_WORK_NAME_FR,
         sw.SOURCE_WORK_YEAR, sw.POSTER_PATH, sw.WIKIPEDIA_IMAGE_PATH,
         CONCAT('m', j.ID_MOVIE) AS CHILD_KEY,
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END AS PARENT_KEY
  FROM T_WC_T2S_MOVIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
  UNION ALL
  SELECT 'serie', j.ID_SERIE, j.DISPLAY_ORDER, sw.ID_SOURCE_WORK, sw.SOURCE_WORK_TYPE,
         sw.SOURCE_WORK_FORM, sw.ID_MOVIE, sw.ID_SERIE, sw.SOURCE_WORK_NAME, sw.SOURCE_WORK_NAME_FR,
         sw.SOURCE_WORK_YEAR, sw.POSTER_PATH, sw.WIKIPEDIA_IMAGE_PATH,
         CONCAT('s', j.ID_SERIE),
         CASE WHEN sw.ID_MOVIE IS NOT NULL THEN CONCAT('m', sw.ID_MOVIE)
              WHEN sw.ID_SERIE IS NOT NULL THEN CONCAT('s', sw.ID_SERIE)
              ELSE CONCAT('w', sw.ID_SOURCE_WORK) END
  FROM T_WC_T2S_SERIE_SOURCE_WORK j JOIN T_WC_T2S_SOURCE_WORK sw ON sw.ID_SOURCE_WORK = j.ID_SOURCE_WORK
  WHERE COALESCE(j.DELETED, 0) = 0 AND COALESCE(sw.DELETED, 0) = 0
)
SELECT l.CHILD_TYPE, l.CHILD_ID, l.DISPLAY_ORDER, l.ID_SOURCE_WORK, l.SOURCE_WORK_TYPE, l.SOURCE_WORK_FORM,
       l.ID_MOVIE, l.ID_SERIE, l.SOURCE_WORK_NAME, l.SOURCE_WORK_NAME_FR, l.SOURCE_WORK_YEAR, l.POSTER_PATH,
       l.WIKIPEDIA_IMAGE_PATH
FROM links l
WHERE l.CHILD_KEY IN (SELECT NODE FROM nodes) OR l.PARENT_KEY IN (SELECT NODE FROM nodes)
ORDER BY l.CHILD_TYPE, l.CHILD_ID, l.ID_SOURCE_WORK;

