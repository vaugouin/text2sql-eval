)
SELECT 'movie' AS NODE_TYPE, m.ID_MOVIE AS ID, m.MOVIE_TITLE AS TITLE, m.MOVIE_TITLE_FR AS TITLE_FR,
       m.RELEASE_YEAR AS YEAR, m.POSTER_PATH
FROM T_WC_T2S_MOVIE m WHERE CONCAT('m', m.ID_MOVIE) IN (SELECT NODE FROM touched)
UNION ALL
SELECT 'serie', s.ID_SERIE, s.SERIE_TITLE, s.SERIE_TITLE_FR, s.FIRST_AIR_YEAR, s.POSTER_PATH
FROM T_WC_T2S_SERIE s WHERE CONCAT('s', s.ID_SERIE) IN (SELECT NODE FROM touched)
ORDER BY 1, 2;

