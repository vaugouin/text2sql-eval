-- check-vision-samples.sql: state of the image evaluations (INPUT_KIND = 'image') before they are
-- shown as samples on the t2s-front search page. Read-only.

-- 1. Image evaluations by flag
SELECT IS_SAMPLE, IS_EVAL, IS_SHOWCASE, DELETED, COUNT(*) AS N
FROM T_WC_T2S_EVALUATION
WHERE INPUT_KIND = 'image'
GROUP BY IS_SAMPLE, IS_EVAL, IS_SHOWCASE, DELETED;

-- 2. Their categories (the samples tree of the search page starts at category 1)
SELECT c.ID_T2S_EVALUATION_CATEGORY, c.ID_PARENT, c.DESCRIPTION, c.DESCRIPTION_FR, c.DELETED, c.DISPLAY_ORDER,
       COUNT(e.ID_T2S_EVALUATION) AS N_IMAGE_EVALS
FROM T_WC_T2S_EVALUATION_CATEGORY c
LEFT JOIN T_WC_T2S_EVALUATION e ON e.ID_T2S_EVALUATION_CATEGORY = c.ID_T2S_EVALUATION_CATEGORY AND e.INPUT_KIND = 'image'
WHERE c.ID_T2S_EVALUATION_CATEGORY BETWEEN 60 AND 75 OR c.ID_T2S_EVALUATION_CATEGORY IN (SELECT ID_PARENT FROM T_WC_T2S_EVALUATION_CATEGORY WHERE ID_T2S_EVALUATION_CATEGORY = 63)
GROUP BY c.ID_T2S_EVALUATION_CATEGORY, c.ID_PARENT, c.DESCRIPTION, c.DESCRIPTION_FR, c.DELETED, c.DISPLAY_ORDER
ORDER BY c.ID_T2S_EVALUATION_CATEGORY;

-- 3. Executions of the image evaluations, by API version and models
SELECT x.API_VERSION, x.ENTITY_EXTRACTION_MODEL, x.TEXT2SQL_MODEL, x.VISION_MODEL,
       COUNT(*) AS N, SUM(x.ASSERTIONS_TOTAL_SCORE IS NOT NULL AND x.ASSERTIONS_TOTAL_SCORE <> 0) AS N_TOTAL_SCORE_SET,
       SUM(x.ASSERTIONS_VISION_IDENTIFICATION_SCORE IS NOT NULL) AS N_VISION_SCORED
FROM T_WC_T2S_EVALUATION_EXECUTION x
JOIN T_WC_T2S_EVALUATION e ON e.ID_T2S_EVALUATION = x.ID_T2S_EVALUATION
WHERE e.INPUT_KIND = 'image' AND x.DELETED = 0
GROUP BY x.API_VERSION, x.ENTITY_EXTRACTION_MODEL, x.TEXT2SQL_MODEL, x.VISION_MODEL
ORDER BY x.API_VERSION DESC;

-- 4. Ten examples
SELECT ID_T2S_EVALUATION, ID_T2S_EVALUATION_CATEGORY, IS_SAMPLE, QUESTION, QUESTION_FR, INPUT_IMAGE_PATH,
       LEFT(ASSERTIONS_VISION_IDENTIFICATION, 120) AS EXPECTED
FROM T_WC_T2S_EVALUATION
WHERE INPUT_KIND = 'image'
ORDER BY ID_T2S_EVALUATION
LIMIT 10;
